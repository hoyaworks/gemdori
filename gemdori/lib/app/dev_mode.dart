//  주요 기능 : 개발자 패널·치트처럼 **실서비스에 나가면 안 되는 것**의 on/off
//  제외 사항 : 무엇을 보여줄지 (그건 각 화면이 정한다)
//
//  상세 설명 : 지금은 배포 계획이 없지만, 나중에 실서비스로 넘길 때
//    「지울 곳을 찾아다니는 일」이 없어야 한다. 그래서 판별을 여기 한 줄로 모은다.
//
//  주요 로직 : 기본값이 **`!kReleaseMode`** 다 — 즉 릴리스 빌드면 저절로 꺼진다.
//    끄는 것을 사람이 기억해야 하는 구조면 언젠가 반드시 빠뜨린다.
//    꺼진 채로 빌드하면 패널 코드는 **트리 셰이킹으로 결과물에서 통째로 빠진다**
//    (참조가 `if (devMode)` 하나뿐이고 그 값이 컴파일 시점에 false 로 정해지므로).
//
//  주요 로직 : `--dart-define=DEV=false` 로 **개발 중에도 실서비스 화면을 미리 볼 수 있다.**
//    반대로 `DEV=true` 면 릴리스 빌드에서도 켤 수 있다 — 시연용 웹 배포에 쓴다.
//
//    실서비스 빌드   flutter build web --release            (자동으로 꺼짐)
//    미리 보기      flutter run -d chrome --dart-define=DEV=false
//    시연용         flutter build web --release --dart-define=DEV=true
//
// ═══════════════════════════════════════════════════════════════════

import 'package:flutter/foundation.dart';

