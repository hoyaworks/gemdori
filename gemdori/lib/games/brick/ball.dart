import 'dart:ui';

class Ball {
  Ball({required this.pos, required this.velocity});

  Offset pos;

  /// 초당 이동 픽셀
  Offset velocity;

  Ball copyWith({Offset? pos, Offset? velocity}) => Ball(
        pos: pos ?? this.pos,
        velocity: velocity ?? this.velocity,
      );
}
