//  주요 기능 : 격자 위치(행·열)와 남은 내구도를 갖는다
//  제외 사항 : 픽셀 좌표 · 색 (좌표는 BrickState, 색은 Painter 가 정한다)
//
//  주요 로직 : 좌표(픽셀)를 갖지 않고 격자 위치(행·열)만 갖는다.
//    창 크기를 바꾸거나 세로/가로가 바뀌면 픽셀 좌표는 전부 다시 계산해야 하는데,
//    벽돌이 좌표를 들고 있으면 그때 '어디가 깨졌는지'까지 같이 날아간다.
//    행·열만 들고 있으면 실제 사각형은 BrickState.brickRect() 가 그때그때 만들고,
//    깨진 상태는 화면 크기와 무관하게 그대로 남는다.
//
//  주요 로직 : 색을 따로 저장하지 않고 남은 내구도(hp)로 정한다.
//    3 = red / 2 = yellow / 1 = blue.
//    맞을 때마다 hp 가 줄어들면 색도 저절로 red → yellow → blue 로 바뀌므로
//    "몇 번 더 때려야 하는가"가 화면에 그대로 보인다. 상태가 한 곳에만 있으니
//    색과 내구도가 어긋날 일도 없다.
//
// ═══════════════════════════════════════════════════════════════════

import 'item.dart';

/// 벽돌 하나. 격자 위치(행·열)와 남은 내구도, 품고 있는 아이템을 갖는다.
class Brick {
  Brick(this.row, this.col, this.hp, {this.item});

  final int row;
  final int col;

  /// 남은 충돌 횟수. 0 이 되면 사라진다.
  int hp;

  /// 품고 있는 아이템. 완전히 깨질 때 떨어뜨린다.
  /// 화면에는 아이콘으로 미리 표시한다 — 먼저 깨거나 피하는 선택이 생기도록.
  /// 이 벽돌에 든 아이템. 부활한 벽돌은 비워 두므로 final 이 아니다 (2026-09-04)
  ItemType? item;

  bool get alive => hp > 0;
}
